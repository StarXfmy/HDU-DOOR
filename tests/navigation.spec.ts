async function fillService(page: Page, name: string, url = 'https://www.hdu.edu.cn/', description = '课程资源与个人笔记') {
  await page.getByLabel('服务名称', { exact: false }).fill(name)
  await page.getByLabel('网址', { exact: false }).fill(url)
  await page.getByLabel('内容介绍', { exact: true }).fill(description)
}
async function importJson(page: Page, value: unknown) {
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('导入个人备份文件', { exact: true }).setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) })
}

